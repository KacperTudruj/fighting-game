import './style.css';
import { Fighter } from '../engine/combat/Fighter';
import { GameEngine } from '../engine/core/GameEngine';
import { GameLoop } from '../engine/core/loop/GameLoop';
import { GameLoopRunner } from '../engine/browser/loop/GameLoopRunner';
import { CanvasRenderer } from '../engine/browser/rendering/CanvasRenderer';
import { Game } from '../game/Game';
import { justRandomePlayer } from '../game/fighters/just-randome-player/definition';
import { neo } from '../game/fighters/neo/definition';
import { smith } from '../game/fighters/smith/definition';
import { KeyboardInputProvider } from '../engine/browser/input/KeyboardInputProvider';
import { parseControls } from '../game/input/Controls';
import { arena } from '../game/arena';
import { selectCharacters, keyLabel } from '../game/ui/CharacterSelection';

const root = document.querySelector<HTMLElement>('#app')!;
async function start(): Promise<void> {
    const response = await fetch(`${import.meta.env.BASE_URL}controls.txt`, {cache:'no-store'});
    if (!response.ok) throw new Error('Nie udało się wczytać controls.txt');
    const controls = parseControls(await response.text());
    const definitions = await selectCharacters(root, [justRandomePlayer, neo, smith], controls);
    root.innerHTML = '<p role="status">Przygotowywanie areny…</p>';
    const canvas = document.createElement('canvas');
    canvas.width = 1280; canvas.height = 720; canvas.className = 'game-canvas';
    canvas.setAttribute('aria-label', 'Arena dwóch graczy');
    canvas.style.background = `linear-gradient(to bottom, #202d25 ${arena.floorY/canvas.height*100}%, #45584a ${arena.floorY/canvas.height*100}%)`;
    const renderer = new CanvasRenderer(canvas);
    const sources = new Set(definitions.flatMap(def => [def.sprite.source, ...def.sprite.frames.map(frame => frame.source ?? def.sprite.source)]));
    await Promise.all([...sources].map(source => renderer.loadSprite(source)));
    const fighter = new Fighter(320, arena.floorY, definitions[0]);
    const opponent = new Fighter(960, arena.floorY, definitions[1]);
    fighter.grounded = opponent.grounded = true;
    const input = new KeyboardInputProvider(controls.player1);
    const input2 = new KeyboardInputProvider(controls.player2);
    const engine = new GameEngine(renderer, [{fighter,input},{fighter:opponent,input:input2}], arena);
    const header = document.createElement('header'); header.className = 'arena-header';
    const heading = document.createElement('h1'); heading.textContent = `${definitions[0].name}  vs  ${definitions[1].name}`;
    const reset = document.createElement('button'); reset.textContent = 'Zmień postacie'; reset.onclick = () => window.location.reload();
    header.append(heading, reset);
    const hint = document.createElement('p'); hint.className = 'keys-hint';
    hint.textContent = [controls.player1, controls.player2].map((keys,index) => `P${index+1}: ${keyLabel(keys.left)}/${keyLabel(keys.right)} ruch · ${keyLabel(keys.jump)} skok · ${keyLabel(keys.crouch)} kucanie`).join('     |     ');
    root.replaceChildren(header, canvas, hint);
    new Game(new GameLoopRunner(new GameLoop(engine))).start();
}
start().catch((error: unknown) => {
    console.error('Nie udało się uruchomić gry', error);
    const message = document.createElement('p'); message.className = 'error';
    message.textContent = 'Nie udało się uruchomić gry. Sprawdź controls.txt i dostępność grafiki; szczegóły w konsoli. Odśwież stronę, aby spróbować ponownie.';
    root.replaceChildren(message);
});
